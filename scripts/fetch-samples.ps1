# 从 DeepPCB 官方仓拉小样到 data/samples（默认 4 对；大数据不进 git）
param(
    [int]$Count = 4,
    [string]$Group = "group00041",
    [string]$Sub = "00041"
)

$ErrorActionPreference = "Stop"
$root = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
if (-not (Test-Path (Join-Path $PSScriptRoot "..\data"))) {
    $root = Resolve-Path (Join-Path $PSScriptRoot "..")
} else {
    $root = Resolve-Path (Join-Path $PSScriptRoot "..")
}
$out = Join-Path $root "data\samples"
New-Item -ItemType Directory -Force -Path $out | Out-Null

$baseImg = "https://raw.githubusercontent.com/tangsanli5201/DeepPCB/master/PCBData/$Group/$Sub"
$baseAnn = "https://raw.githubusercontent.com/tangsanli5201/DeepPCB/master/PCBData/$Group/${Sub}_not"
$ua = @{ "User-Agent" = "DeepPCB-Station-fetch" }

Write-Host "下载到 $out （最多 $Count 对）"
$api = "https://api.github.com/repos/tangsanli5201/DeepPCB/contents/PCBData/$Group/$Sub`?ref=master"
$items = Invoke-RestMethod -Uri $api -Headers $ua
$temps = $items | Where-Object { $_.name -match '_temp\.jpg$' } | Select-Object -First $Count
$stems = @()
foreach ($it in $temps) {
    $stem = $it.name -replace '_temp\.jpg$', ''
    $stems += $stem
    foreach ($pair in @(
        @{ Url = "$baseImg/${stem}_temp.jpg"; Dest = Join-Path $out "${stem}_temp.jpg" },
        @{ Url = "$baseImg/${stem}_test.jpg"; Dest = Join-Path $out "${stem}_test.jpg" },
        @{ Url = "$baseAnn/${stem}.txt"; Dest = Join-Path $out "${stem}.txt" }
    )) {
        Invoke-WebRequest -Uri $pair.Url -OutFile $pair.Dest -UseBasicParsing -Headers $ua
        Write-Host "  OK $(Split-Path $pair.Dest -Leaf)"
    }
}

$man = Join-Path $out "Manifest.txt"
@(
    "# auto-generated by fetch-samples.ps1",
    "# DeepPCB samples ≤100 pairs"
) + $stems | Set-Content $man -Encoding UTF8
Write-Host "Manifest → $man ($($stems.Count) stems)"
